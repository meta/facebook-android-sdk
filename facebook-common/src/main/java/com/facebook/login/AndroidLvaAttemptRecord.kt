package com.facebook.login

import android.content.Context
import android.content.SharedPreferences
import com.facebook.FacebookSdk
import java.util.UUID
import java.util.concurrent.TimeUnit
import org.json.JSONObject

/**
 * The record of the single active Android SDK Login Via App (LVA) attempt, kept in SDK-private
 * SharedPreferences so it survives recreation, process death and task clearing. The callback entry
 * points consult it before forwarding a callback, and only an attempt that is still live may
 * receive one. A terminal attempt's record is cleared, never kept.
 *
 * Every change rechecks the attempt's state and version, so an older activity or a stale cleanup
 * can never change or erase a newer attempt, or one that Continue refreshed. Nothing here throws: a
 * failed write returns null or false, and a failed read means no record.
 */
internal object AndroidLvaAttemptRecord {
  /** The extras every enhanced attempt's result Intent carries, so its launch can be identified. */
  const val RESULT_EXTRA_STATE = "com.facebook.login.AndroidLvaAttemptRecord.state"
  const val RESULT_EXTRA_LAUNCH_NONCE = "com.facebook.login.AndroidLvaAttemptRecord.launch_nonce"

  private const val PREFS_STORE = "com.facebook.login.AndroidLvaAttemptRecord"
  private const val ACTIVE_ATTEMPT = "active_attempt"
  private val LAUNCH_WINDOW_MS = TimeUnit.MINUTES.toMillis(30)
  private val PENDING_WINDOW_MS = TimeUnit.MINUTES.toMillis(10)

  enum class Phase {
    LAUNCHED,
    PENDING
  }

  data class Record(
      val state: String,
      val version: Int,
      val phase: Phase,
      val authLoggerId: String,
      val arm: String,
      // Generated by the SDK at launch, never taken from the caller; Continue keeps it.
      val launchNonce: String,
      val expiresAt: Long
  )

  /**
   * Starts the record of a new attempt, replacing any earlier one, with a new launch nonce and a
   * 30-minute launch window. Returns null if it couldn't be stored.
   */
  @Synchronized
  fun launch(
      state: String,
      authLoggerId: String,
      arm: String,
      now: Long = System.currentTimeMillis()
  ): Record? =
      store(
          Record(
              state = state,
              version = 1,
              phase = Phase.LAUNCHED,
              authLoggerId = authLoggerId,
              arm = arm,
              launchNonce = UUID.randomUUID().toString(),
              expiresAt = now + LAUNCH_WINDOW_MS))

  /**
   * Moves the attempt to PENDING when the SDK activity resumes without a result. The pending
   * deadline is set only once, 10 minutes after first entering PENDING, and becomes the expiry.
   * Returns the new record, or null if [state] and [version] no longer match a live record.
   */
  @Synchronized
  fun enterPending(state: String, version: Int, now: Long = System.currentTimeMillis()): Record? {
    val record = readMatching(state, version, now) ?: return null
    if (record.phase == Phase.PENDING) {
      return record
    }
    return store(record.copy(phase = Phase.PENDING, expiresAt = now + PENDING_WINDOW_MS))
  }

  /**
   * Continue: the same logical launch, with the same state and launch nonce, gets a fresh 30-minute
   * launch window and a new version. Returns the new record, or null if [state] and [version] no
   * longer match a live PENDING record.
   */
  @Synchronized
  fun continueLaunch(state: String, version: Int, now: Long = System.currentTimeMillis()): Record? {
    val record = readMatching(state, version, now) ?: return null
    if (record.phase != Phase.PENDING) {
      return null
    }
    return store(
        record.copy(
            version = record.version + 1,
            phase = Phase.LAUNCHED,
            expiresAt = now + LAUNCH_WINDOW_MS))
  }

  /** The stored record, live or expired, or null if there is none or it can't be read. */
  @Synchronized
  fun read(): Record? =
      try {
        getPreferences()?.getString(ACTIVE_ATTEMPT, null)?.let { parse(JSONObject(it)) }
      } catch (e: Exception) {
        null
      }

  fun isLive(record: Record, now: Long = System.currentTimeMillis()): Boolean =
      now < record.expiresAt

  /**
   * Removes the record only if both [state] and [version] still match. A caller that is clearing an
   * expired record passes [expiredAt], its current time: the record is then removed only if it is
   * still expired, because entering PENDING extends the expiry without changing the version.
   * Returns whether it removed one.
   */
  @Synchronized
  fun clearIf(state: String, version: Int, expiredAt: Long? = null): Boolean {
    val record = read() ?: return false
    if (record.state != state ||
        record.version != version ||
        (expiredAt != null && isLive(record, expiredAt))) {
      return false
    }
    return try {
      getPreferences()?.edit()?.remove(ACTIVE_ATTEMPT)?.commit() ?: false
    } catch (e: Exception) {
      false
    }
  }

  private fun readMatching(state: String, version: Int, now: Long): Record? =
      read()?.takeIf { it.state == state && it.version == version && isLive(it, now) }

  // commit, not apply: the record is the authority the entry points read, also after process death.
  private fun store(record: Record): Record? {
    val json =
        JSONObject()
            .put("state", record.state)
            .put("version", record.version)
            .put("phase", record.phase.name)
            .put("auth_logger_id", record.authLoggerId)
            .put("arm", record.arm)
            .put("launch_nonce", record.launchNonce)
            .put("expires_at", record.expiresAt)
    val stored =
        try {
          getPreferences()?.edit()?.putString(ACTIVE_ATTEMPT, json.toString())?.commit() ?: false
        } catch (e: Exception) {
          false
        }
    return if (stored) record else null
  }

  private fun parse(json: JSONObject): Record =
      Record(
          state = json.getString("state"),
          version = json.getInt("version"),
          phase = Phase.valueOf(json.getString("phase")),
          authLoggerId = json.getString("auth_logger_id"),
          arm = json.getString("arm"),
          launchNonce = json.getString("launch_nonce"),
          expiresAt = json.getLong("expires_at"))

  private fun getPreferences(): SharedPreferences? {
    // A nullable local keeps this guard: without a context there is no record.
    val context: Context? = FacebookSdk.getApplicationContext()
    return context?.getSharedPreferences(PREFS_STORE, Context.MODE_PRIVATE)
  }
}
